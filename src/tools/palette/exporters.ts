/* Palette exports: CSS custom properties, design tokens (DTCG 2025.10 JSON), Figma variables (the
   REST API's POST /v1/files/:key/variables payload), a Tailwind config, and Adobe Swatch Exchange. */
import { hexToRgb } from '../../lib/color';
import { fmtOklch, type Step } from './scales';

export interface NamedScale { name: string; hex: string; steps: Step[] }

export const slug = (s: string) => s.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'color';

export function toCss(scales: NamedScale[], o: { prefix: string; format: 'hex' | 'oklch'; withScales: boolean }): string {
  const lines = [':root {'];
  for (const s of scales) {
    const n = `--${o.prefix ? o.prefix + '-' : ''}${slug(s.name)}`;
    const base = s.steps.find(x => x.base);
    lines.push(`  ${n}: ${o.format === 'oklch' && base ? fmtOklch(base.lch) : s.hex};`);
    if (o.withScales) for (const st of s.steps) lines.push(`  ${n}-${st.step}: ${o.format === 'oklch' ? fmtOklch(st.lch) : st.hex};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const comps = (hex: string) => (hexToRgb(hex) ?? [0, 0, 0]).map(v => Math.round(v / 255 * 10000) / 10000);
const dtcgColor = (hex: string) => ({ $type: 'color', $value: { colorSpace: 'srgb', components: comps(hex), hex: hex.toLowerCase() } });

export function toDtcg(scales: NamedScale[], withScales: boolean): string {
  const color: Record<string, unknown> = {};
  for (const s of scales) {
    const k = slug(s.name);
    color[k] = withScales
      ? { ...dtcgColor(s.hex), ...Object.fromEntries(s.steps.map(st => [String(st.step), dtcgColor(st.hex)])) }
      : dtcgColor(s.hex);
  }
  return JSON.stringify({ $schema: 'https://www.designtokens.org/schemas/2025.10/format.json', color }, null, 2) + '\n';
}

/** Figma REST API variables payload: one collection, one mode, a COLOR variable per swatch (and step). */
export function toFigma(scales: NamedScale[], o: { collection: string; withScales: boolean }): string {
  const variables: unknown[] = [], values: unknown[] = [];
  const add = (name: string, hex: string) => {
    const id = `var_${variables.length + 1}`;
    const [r, g, b] = comps(hex);
    variables.push({ action: 'CREATE', id, name, variableCollectionId: 'collection', resolvedType: 'COLOR', scopes: ['ALL_SCOPES'] });
    values.push({ variableId: id, modeId: 'mode', value: { r, g, b, a: 1 } });
  };
  for (const s of scales) {
    add(o.withScales ? `${slug(s.name)}/base` : slug(s.name), s.hex);
    if (o.withScales) for (const st of s.steps) add(`${slug(s.name)}/${st.step}`, st.hex);
  }
  return JSON.stringify({
    variableCollections: [{ action: 'CREATE', id: 'collection', name: o.collection, initialModeId: 'mode' }],
    variableModes: [{ action: 'UPDATE', id: 'mode', name: 'Default', variableCollectionId: 'collection' }],
    variables, variableModeValues: values,
  }, null, 2) + '\n';
}

export function toTailwind(scales: NamedScale[], withScales: boolean): string {
  const colors = Object.fromEntries(scales.map(s => [slug(s.name), withScales
    ? { DEFAULT: s.hex, ...Object.fromEntries(s.steps.map(st => [st.step, st.hex])) } : s.hex]));
  return `/** Generated by Lathe Palette. Tailwind v3 config; in v4, load it with @config. */\nmodule.exports = {\n  theme: {\n    extend: {\n      colors: ${JSON.stringify(colors, null, 2).replace(/\n/g, '\n      ')},\n    },\n  },\n};\n`;
}

/**
 * Adobe Swatch Exchange (.ase, version 1.0): "ASEF", version, block count, then blocks. Colors are
 * RGB float32 (0–1), "global" type; with scales, each swatch's steps sit in a named group.
 */
export function toAse(scales: NamedScale[], withScales: boolean): Uint8Array {
  const blocks: Uint8Array[] = [];
  const nameBytes = (name: string) => {
    const b = new Uint8Array(2 + (name.length + 1) * 2); const v = new DataView(b.buffer);
    v.setUint16(0, name.length + 1);
    for (let i = 0; i < name.length; i++) v.setUint16(2 + i * 2, name.charCodeAt(i));
    return b;
  };
  const block = (type: number, body: Uint8Array) => {
    const b = new Uint8Array(6 + body.length); const v = new DataView(b.buffer);
    v.setUint16(0, type); v.setUint32(2, body.length); b.set(body, 6);
    blocks.push(b);
  };
  const color = (name: string, hex: string) => {
    const nb = nameBytes(name);
    const body = new Uint8Array(nb.length + 4 + 12 + 2); const v = new DataView(body.buffer);
    body.set(nb, 0);
    'RGB '.split('').forEach((c, i) => v.setUint8(nb.length + i, c.charCodeAt(0)));
    comps(hex).forEach((c, i) => v.setFloat32(nb.length + 4 + i * 4, c));
    v.setUint16(nb.length + 16, 0); // global
    block(0x0001, body);
  };
  for (const s of scales) {
    if (!withScales) { color(s.name, s.hex); continue; }
    block(0xc001, nameBytes(s.name));
    color(s.name, s.hex);
    for (const st of s.steps) color(`${s.name} ${st.step}`, st.hex);
    block(0xc002, new Uint8Array(0));
  }
  const total = 12 + blocks.reduce((n, b) => n + b.length, 0);
  const out = new Uint8Array(total); const v = new DataView(out.buffer);
  'ASEF'.split('').forEach((c, i) => v.setUint8(i, c.charCodeAt(0)));
  v.setUint16(4, 1); v.setUint16(6, 0); v.setUint32(8, blocks.length);
  let off = 12; for (const b of blocks) { out.set(b, off); off += b.length; }
  return out;
}
